import { expect, test } from "@playwright/test";

// Run only with playwright.in-focus.config.ts and the isolated model-fixture server.
test.beforeEach(async ({ page, baseURL }) => {
  test.skip(baseURL !== "http://127.0.0.1:3510", "Requires the isolated In Focus review server");
  await page.request.post("/api/admin/auth", { data: { password: "local-in-focus-review" } });
});

test("admin workshop: research, generation, revision, comparison and privacy", async ({ page, browser }) => {
  const errors: string[] = [];
  page.on("pageerror", (error) => errors.push(error.message));
  await page.goto("/admin/in-focus");
  await expect(page.getByRole("heading", { name: "In Focus Workshop", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "New experiment", exact: true }).click();
  const title = `Cooling a city · browser review ${Date.now()}`;
  await page.getByLabel("Working title").fill(title);
  await page.getByRole("button", { name: "Create experiment", exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/in-focus\/[\w-]+$/);
  const id = page.url().split("/").at(-1)!;
  await page.getByLabel("What are you trying to understand?").fill("How should a citizen judge the council's priorities?");
  await page.getByRole("button", { name: "Add first source" }).click();
  await page.getByLabel("Source title", { exact: true }).fill("Council statement");
  await page.getByLabel("Source URL (optional)").fill("https://example.com/council");
  await page.getByLabel("Relevant excerpts or research notes").fill("The council is considering cooling centres with a limited budget. Some residents face more exposure than others.");
  await page.getByRole("button", { name: "Save experiment", exact: true }).click();
  await expect(page.getByText("Experiment saved.", { exact: true })).toBeVisible();
  await page.screenshot({ path: ".local-review/in-focus-sources.png", fullPage: true });
  await page.getByRole("button", { name: "2. Briefing", exact: true }).click();
  await page.getByRole("button", { name: "Generate briefing", exact: true }).click();
  await expect(page.getByText("New alternative saved and selected.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit text", exact: true }).click();
  await page.getByLabel("Briefing text", { exact: true }).fill("An edited briefing: cooling centres are proposed, but the allocation is contested. [S1]");
  await page.getByRole("button", { name: "3. Discussion", exact: true }).click();
  await expect(page.getByRole("dialog", { name: "Discard unsaved text?" })).toBeVisible();
  await page.getByRole("button", { name: "Cancel", exact: true }).click();
  await expect(page.getByLabel("Briefing text", { exact: true })).toHaveValue(/An edited briefing/);
  await page.getByRole("button", { name: "Save reviewed briefing", exact: true }).click();
  await expect(page.getByText("Edited alternative saved.", { exact: false })).toBeVisible();
  await page.getByRole("button", { name: "Edit text", exact: true }).click();
  await page.getByLabel("Briefing text", { exact: true }).fill("Unsaved text to discard");
  await page.getByRole("button", { name: "Reload", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Discard changes", exact: true }).click();
  await expect(page.getByText("Latest saved experiment loaded.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Edit text", exact: true }).click();
  await expect(page.getByLabel("Briefing text", { exact: true })).toHaveValue(/An edited briefing/);
  await page.getByRole("button", { name: "3. Discussion", exact: true }).click();
  await page.getByRole("button", { name: "Suggest questions", exact: true }).click();
  await page.getByRole("button", { name: "Use this question", exact: true }).first().click();
  await page.getByRole("button", { name: "Suggest philosophers", exact: true }).click();
  await page.getByRole("button", { name: "Use as main", exact: true }).first().click();
  await page.getByRole("button", { name: "Use as challenger", exact: true }).last().click();
  await page.getByRole("button", { name: "Generate main argument", exact: true }).click();
  await expect(page.getByText("New alternative saved and selected.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "2. Challenge", exact: true }).click();
  await page.getByRole("button", { name: "Generate challenge", exact: true }).click();
  await expect(page.getByText("New alternative saved and selected.", { exact: true })).toBeVisible();
  await page.screenshot({ path: ".local-review/in-focus-discussion.png", fullPage: true });
  await page.getByRole("button", { name: "3. Reply (optional)", exact: true }).click();
  await page.getByRole("button", { name: "Generate reply", exact: true }).click();
  await expect(page.getByText("New alternative saved and selected.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Reading preview", exact: true }).click();
  await expect(page.getByText("An edited briefing:", { exact: false })).toBeVisible();
  await page.screenshot({ path: ".local-review/in-focus-preview.png", fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Saved alternatives", exact: true }).click();
  await page.getByLabel("Filter by step").selectOption("briefing");
  await page.getByRole("button", { name: "Inspect / compare", exact: true }).last().click();
  await expect(page.getByRole("heading", { name: "Currently selected", exact: true })).toBeVisible();
  await expect(page.getByRole("dialog").getByText("Council statement", { exact: false })).toBeAttached();
  await page.screenshot({ path: ".local-review/in-focus-comparison.png", fullPage: true });
  await page.getByRole("button", { name: "Close", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: "1. Sources", exact: true }).click();
  await expect(page.getByLabel("Source title", { exact: true })).toHaveValue("Council statement");
  await page.getByLabel("Relevant excerpts or research notes").fill("The council has changed the budget and eligibility rules.");
  await expect(page.getByText(/^Earlier context:/)).toBeVisible();
  await page.getByRole("button", { name: "Save experiment", exact: true }).click();
  await page.getByRole("button", { name: "2. Briefing", exact: true }).click();
  await page.getByRole("button", { name: "Generate another alternative", exact: true }).click();
  await expect(page.getByText("New alternative saved and selected.", { exact: true })).toBeVisible();
  const before = (await (await page.request.get(`/api/admin/in-focus/${id}`)).json()).experiment;
  await page.getByLabel("Editorial feedback (optional)").fill("FAIL_REVIEW_TEST");
  await page.getByRole("button", { name: "Generate another alternative", exact: true }).click();
  await expect(page.getByRole("alert").filter({ hasText: "outside the supplied material" })).toBeVisible();
  const after = (await (await page.request.get(`/api/admin/in-focus/${id}`)).json()).experiment;
  expect(after.state.selected.briefing).toBe(before.state.selected.briefing);
  await page.getByRole("button", { name: "Archive", exact: true }).click();
  await page.getByRole("dialog").getByRole("button", { name: "Archive experiment", exact: true }).click();
  await expect(page.getByText("Experiment archived.", { exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Restore experiment", exact: true }).click();
  await expect(page.getByText("Experiment restored.", { exact: true })).toBeVisible();
  const guest = await browser.newContext();
  const response = await guest.request.get(`http://127.0.0.1:3510/api/admin/in-focus/${id}`);
  expect(response.status()).toBe(401);
  const guestPage = await guest.newPage();
  await guestPage.goto(`http://127.0.0.1:3510/admin/in-focus/${id}`);
  await expect(guestPage).toHaveURL(/\/admin\/login$/);
  await guestPage.goto("http://127.0.0.1:3510/");
  await expect(guestPage.getByRole("link", { name: "Explore the question" })).toBeVisible();
  await expect(guestPage.getByText(title, { exact: true })).toHaveCount(0);
  await guest.close();
  expect(errors).toEqual([]);
});
